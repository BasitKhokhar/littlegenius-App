#!/usr/bin/env node
// downloadQuranAudio.mjs — BUILD-TIME fetch of real Qari recitation for the
// Quran content the app teaches (Juz Amma + Al-Fatiha, ~86 short ayaat).
//
// Unlike device TTS, a real reciter applies proper tajweed — essential for a
// kids app that teaches correct recitation. We use the "Husary Muallim"
// (teaching) recitation: slow and clear, made for learners to repeat.
//
// It reads every ayah from src/Data/juzAmmaData.js, downloads each ayah's MP3
// from everyayah.com into assets/audio/quran/<surahId>_<n>.mp3, and regenerates
// src/Utils/quranAudioManifest.generated.js so React Native can require() them.
//
// This runs on a developer machine, NOT in the app. Nothing here ships except
// the resulting MP3s + manifest.
//
// Usage:
//   node scripts/downloadQuranAudio.mjs                 # download + manifest
//   node scripts/downloadQuranAudio.mjs --manifest-only # rebuild manifest only
//   node scripts/downloadQuranAudio.mjs --check         # probe one URL, no bulk
//
// Prereq: Node 18+ (global fetch), internet access.
import esbuild from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'assets', 'audio', 'quran');
const MANIFEST = path.join(ROOT, 'src', 'Utils', 'quranAudioManifest.generated.js');

// everyayah.com reciter folder. Husary Muallim = slow, clear teaching recitation.
const RECITER = 'Husary_Muallim_128kbps';
const BASE = `https://everyayah.com/data/${RECITER}`;

const args = process.argv.slice(2);
const has = (f) => args.includes(f);
const MANIFEST_ONLY = has('--manifest-only');
const CHECK = has('--check');

const pad3 = (n) => String(n).padStart(3, '0');
// everyayah filename: {surah:3}{ayah:3}.mp3  →  Al-Fatiha ayah 1 = 001001.mp3
const ayahUrl = (surahNumber, ayahN) => `${BASE}/${pad3(surahNumber)}${pad3(ayahN)}.mp3`;

// Load juzAmmaData.js by bundling it (esbuild resolves ESM for Node).
async function loadSurahs() {
  const outfile = path.join(os.tmpdir(), `lg-juz-${Date.now()}.mjs`);
  await esbuild.build({
    entryPoints: [path.join(ROOT, 'src', 'Data', 'juzAmmaData.js')],
    bundle: true,
    format: 'esm',
    platform: 'node',
    outfile,
    logLevel: 'silent',
  });
  const mod = await import(pathToFileURL(outfile).href);
  fs.rmSync(outfile, { force: true });
  return mod.default ?? mod.juzAmmaData;
}

// Regenerate the RN manifest from whatever clips currently exist on disk.
function writeManifest() {
  const files = fs.existsSync(OUT_DIR)
    ? fs.readdirSync(OUT_DIR).filter((f) => f.endsWith('.mp3')).sort()
    : [];
  const lines = files
    .map((f) => {
      // <surahId>_<n>.mp3  →  key "surahId:n"
      const base = f.slice(0, -4);
      const i = base.lastIndexOf('_');
      const key = `${base.slice(0, i)}:${base.slice(i + 1)}`;
      return `  '${key}': require('../../assets/audio/quran/${f}'),`;
    })
    .join('\n');
  const body =
    `// ⚠️  AUTO-GENERATED by scripts/downloadQuranAudio.mjs — DO NOT EDIT BY HAND.\n` +
    `// Maps "<surahId>:<ayahNumber>" -> bundled Qari recitation clip.\n` +
    `// Reciter: ${RECITER} (everyayah.com). Absent keys fall back to device TTS.\n\n` +
    `export const QURAN_AUDIO = {\n${lines}\n};\n\n` +
    `export default QURAN_AUDIO;\n`;
  fs.writeFileSync(MANIFEST, body);
  console.log(`✔ Wrote manifest ${path.relative(ROOT, MANIFEST)} (${files.length} clips)`);
}

async function download(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${res.status} ${res.statusText}`);
  const buf = Buffer.from(await res.arrayBuffer());
  if (buf.length < 512) throw new Error(`suspiciously small (${buf.length} bytes)`);
  return buf;
}

async function main() {
  if (MANIFEST_ONLY) {
    writeManifest();
    return;
  }

  const surahs = await loadSurahs();
  if (!Array.isArray(surahs) || !surahs.length) {
    throw new Error('Could not load juzAmmaData');
  }

  if (CHECK) {
    const s = surahs[0];
    const url = ayahUrl(s.number, s.ayahs[0].n);
    const buf = await download(url);
    console.log(`✔ Reachable: ${url} (${buf.length} bytes)`);
    return;
  }

  fs.mkdirSync(OUT_DIR, { recursive: true });

  let made = 0, skipped = 0, failed = 0, bytes = 0;
  const failures = [];
  for (const surah of surahs) {
    for (const ayah of surah.ayahs || []) {
      const out = path.join(OUT_DIR, `${surah.id}_${ayah.n}.mp3`);
      if (fs.existsSync(out) && fs.statSync(out).size > 512) {
        skipped++;
        bytes += fs.statSync(out).size;
        continue;
      }
      const url = ayahUrl(surah.number, ayah.n);
      try {
        const buf = await download(url);
        fs.writeFileSync(out, buf);
        made++;
        bytes += buf.length;
        if (made % 20 === 0) console.log(`  …${made} clips downloaded`);
      } catch (e) {
        failed++;
        failures.push(`${surah.id} ayah ${ayah.n} (${url}): ${e.message}`);
      }
    }
  }

  console.log(`\nDone. downloaded=${made} skipped=${skipped} failed=${failed}`);
  console.log(`Total size on disk: ${(bytes / 1024 / 1024).toFixed(2)} MB`);
  if (failures.length) {
    console.warn('\nFailures:');
    for (const f of failures) console.warn('  ✖ ' + f);
  }
  writeManifest();
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
